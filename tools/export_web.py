"""Generate web/js/data.js from the Python sources, so the web/Android app never drifts from the
desktop app: version, field map, model names, band library, factory bank, AI prompt and schemas. Run after changing tankg/artists.py:

    .venv/bin/python tools/export_web.py

tests/test_web.py fails while data.js is out of date.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tankg import ai, artists, library  # noqa: E402
from tankg.model import AMP_MODELS, CAB_MODELS, FIELDS, OFF_COLOR, Preset  # noqa: E402
from tankg.version import RELEASES_REPO, __version__  # noqa: E402

OUT = ROOT / "web" / "js" / "data.js"


def render() -> str:
    fields = [{"key": f.key, "offset": f.offset, "label": f.label, "max": f.maximum,
               "verified": f.verified, "zones": list(f.zones)} for f in FIELDS]
    banks = [{"genre": b.genre, "name": b.name,
              "presets": [{"name": p.name, "role": p.role, "desc": p.desc, "summary": p.summary(),
                           # every one of the 21 bytes is mapped, so the record is complete
                           "hex": p.build(Preset(bytearray(21))).to_bytes().hex()} for p in b.presets]}
             for b in artists.BANKS]
    dump = lambda v: json.dumps(v, ensure_ascii=False, separators=(",", ":"))  # noqa: E731
    byte_names = {f.offset: f.label for f in FIELDS}
    byte_names.update({OFF_COLOR: "LED rojo", OFF_COLOR + 1: "LED verde", OFF_COLOR + 2: "LED azul"})
    factory = library.factory_bank()
    ai_data = {"system": ai.system_prompt(), "schema": ai.SCHEMA, "bankSchema": ai.BANK_SCHEMA,
               "bankInstructions": ai.BANK_INSTRUCTIONS, "instruments": ai.INSTRUMENTS,
               "suggestions": ai.SUGGESTIONS, "providers": ai.PROVIDERS, "webSites": ai.WEB_SITES,
               "zones": ai.ZONES}
    return ("// Generated by tools/export_web.py from the tankg package. Do not edit.\n"
            f"export const VERSION = {dump(__version__)};\n"
            f"export const RELEASES_REPO = {dump(RELEASES_REPO)};\n"
            f"export const BYTE_NAMES = {dump([byte_names.get(i, f'byte {i}') for i in range(21)])};\n"
            f"export const FACTORY = {dump(factory.to_bytes().hex() if factory else None)};\n"
            f"export const AI = {dump(ai_data)};\n"
            f"export const AMP_MODELS = {dump(AMP_MODELS)};\n"
            f"export const CAB_MODELS = {dump(CAB_MODELS)};\n"
            f"export const FIELDS = {dump(fields)};\n"
            f"export const ROLE_COLORS = {dump({k: list(v) for k, v in artists.ROLE_COLORS.items()})};\n"
            f"export const LIBRARY = {dump(banks)};\n")


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(artists.BANKS)} bancos")
