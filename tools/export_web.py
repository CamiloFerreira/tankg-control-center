"""Generate web/js/data.js from the Python sources (field map, model names, band library), so
the web/Android app never drifts from the desktop app. Run after changing tankg/artists.py:

    .venv/bin/python tools/export_web.py

tests/test_web.py fails while data.js is out of date.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tankg import artists  # noqa: E402
from tankg.model import AMP_MODELS, CAB_MODELS, FIELDS, Preset  # noqa: E402

OUT = ROOT / "web" / "js" / "data.js"


def render() -> str:
    fields = [{"key": f.key, "offset": f.offset, "label": f.label, "max": f.maximum,
               "verified": f.verified, "zones": list(f.zones)} for f in FIELDS]
    banks = [{"genre": b.genre, "name": b.name,
              "presets": [{"name": p.name, "role": p.role, "desc": p.desc, "summary": p.summary(),
                           # every one of the 21 bytes is mapped, so the record is complete
                           "hex": p.build(Preset(bytearray(21))).to_bytes().hex()} for p in b.presets]}
             for b in artists.BANKS]
    dump = lambda v: json.dumps(v, ensure_ascii=False, separators=(",", ":"))  # noqa: E731
    return ("// Generated by tools/export_web.py from tankg/model.py and tankg/artists.py. Do not edit.\n"
            f"export const AMP_MODELS = {dump(AMP_MODELS)};\n"
            f"export const CAB_MODELS = {dump(CAB_MODELS)};\n"
            f"export const FIELDS = {dump(fields)};\n"
            f"export const ROLE_COLORS = {dump({k: list(v) for k, v in artists.ROLE_COLORS.items()})};\n"
            f"export const LIBRARY = {dump(banks)};\n")


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(artists.BANKS)} bancos")
