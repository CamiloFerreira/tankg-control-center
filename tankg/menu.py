def fold(text: str) -> str:
    """Lower case without accents, for the search (same as fold() in app.js)."""
    return "".join(c for c in unicodedata.normalize("NFD", text) if not unicodedata.combining(c)).lower()


def matches(query: str, haystack: str) -> bool:
    """Every word of the query appears in the item's search text."""
    return all(w in haystack for w in fold(query).split())


def items(desktop: bool = True):
    """(group title, command, label, description, icon, search text) in menu order."""
    for title, _, entries in MENU:
        for cmd, label, desc, icon, keys in entries:
            if not (desktop and cmd in ANDROID_ONLY):
                yield title, cmd, label, desc, icon, fold(f"{title} {label} {desc} {keys}")
